namespace Middag\Demo\Standalone\Tests\Coverage;

/**
 * Renders COVERAGE.md from the coverage manifest and the installed `@api` inventory.
 *
 * The output is deterministic: the same manifest and the same lock give the same
 * bytes, so CI regenerates the file and fails on any diff.
 */
final class CoverageReport
{
    private const array STATUS_LABELS = ['covered' => 'covered', 'host' => 'host', 'gap' => 'gap'];

    /**
     * @param array{covered: array<string, array{kind: string, route: ?string, note: string}>, gaps: array<string, array{reason: string, filed: string}>, api: array<string, array<string, mixed>>, internal?: array<string, string>} $manifest
     * @param array<string, array{lib: string, area: string, kind: string}>                                                                                                                                                           $inventory
     * @param array<string, string>                                                                                                                                                                                                   $versions  library => installed version
     */
    public static function render(array $manifest, array $inventory, array $versions): string
    {
        $out = [];
        $out[] = '# Coverage';
        $out[] = '';
        $out[] = '<!-- Generated by `composer coverage:md` from coverage/manifest.php and the installed libraries. Do not edit by hand. -->';
        $out[] = '';
        $out[] = 'Every `@api` symbol of `middag-io/framework` and `middag-io/ui`, with the demo artifact that exercises it and the test that proves it.';
        $out[] = sprintf('Generated from `middag-io/framework` %s and `middag-io/ui` %s, as installed from `composer.lock`.', $versions['framework'] ?? '?', $versions['ui'] ?? '?');
        $out[] = '';
        $out[] = '- **covered**: the demo uses the symbol, or reaches it through another one; the tests and E2E specs listed prove it.';
        $out[] = '- **host**: a contract a host adapter implements. The moodle and wordpress adapters prove it in their own suites.';
        $out[] = '- **gap**: not proved by the demo, with the reason. A test may still prove that the symbol is emitted when no free renderer consumes it.';
        $out[] = '';
        $out[] = '`ApiCoverageTest` keeps this map in step with the installed libraries: it fails when an `@api` symbol is missing from the map, when the map names a symbol, a test method or an E2E title that does not exist, or when an entry lacks its proof or its reason.';
        $out[] = '';

        $byLib = [];
        foreach ($inventory as $symbol => $facts) {
            $byLib[$facts['lib']][$facts['area']][] = $symbol;
        }

        $out[] = '## Summary';
        $out[] = '';
        $out[] = '| Library | `@api` | covered | host | gap |';
        $out[] = '|---|---|---|---|---|';
        foreach (ApiInventory::LIBRARIES as $lib => $root) {
            $counts = self::counts(array_merge(...array_values($byLib[$lib] ?? [[]])), $manifest['api']);
            $out[] = sprintf('| `middag-io/%s` | %d | %d | %d | %d |', $lib, array_sum($counts), $counts['covered'], $counts['host'], $counts['gap']);
        }
        $out[] = '';

        foreach (ApiInventory::LIBRARIES as $lib => $root) {
            $out[] = sprintf('## `middag-io/%s`', $lib);
            $out[] = '';
            $areas = $byLib[$lib] ?? [];
            ksort($areas);
            foreach ($areas as $area => $symbols) {
                $counts = self::counts($symbols, $manifest['api']);
                $out[] = sprintf('### %s — %d `@api`: %d covered, %d host, %d gap', $area, \count($symbols), $counts['covered'], $counts['host'], $counts['gap']);
                $out[] = '';
                $out[] = '| Symbol | Status | Artifact or reason | Tests | E2E |';
                $out[] = '|---|---|---|---|---|';
                foreach ($symbols as $symbol) {
                    $out[] = self::row(substr($symbol, \strlen($root)), $manifest['api'][$symbol] ?? []);
                }
                $out[] = '';
            }
        }

        $out[] = '## UI wire surface';
        $out[] = '';
        $out[] = 'Block, cell, field, layout and shell types the PHP contract emits and the free React renderer draws. `CoverageManifestTest` boots each route and asserts the type is emitted, that no PRO block leaks and that no catalogued gap is emitted silently.';
        $out[] = '';
        $out[] = '| Symbol | Proof route | Note |';
        $out[] = '|---|---|---|';
        foreach ($manifest['covered'] as $symbol => $entry) {
            $out[] = sprintf('| `%s` | %s | %s |', $symbol, $entry['route'] !== null ? '`' . $entry['route'] . '`' : '—', self::cell($entry['note']));
        }
        $out[] = '';
        $out[] = '| Gap | Reason |';
        $out[] = '|---|---|';
        foreach ($manifest['gaps'] as $symbol => $entry) {
            $out[] = sprintf('| `%s` | %s |', $symbol, self::cell($entry['reason']));
        }
        $out[] = '';
        $out[] = '## Internal classes the demo still names';
        $out[] = '';
        $out[] = 'Classes the framework marks `@internal`. The demo names them only where no `@api` seam covers the need.';
        $out[] = '';
        $out[] = '| Class | Why |';
        $out[] = '|---|---|';
        foreach ($manifest['internal'] ?? [] as $class => $why) {
            $out[] = sprintf('| `%s` | %s |', $class, self::cell($why));
        }
        $out[] = '';
        $out[] = '## Out of scope';
        $out[] = '';
        $out[] = 'The Moodle and WordPress adapters, the transactional outbox, multi-tenancy, organisation scope, licensing, host enforcement of `#[Auth]` and the PRO blocks are not part of the OSS surface the demo proves. The adapters keep their own coverage in their repositories.';

        return implode("\n", $out) . "\n";
    }

    /**
     * @param list<string>                        $symbols
     * @param array<string, array<string, mixed>> $api
     *
     * @return array{covered: int, host: int, gap: int}
     */
    private static function counts(array $symbols, array $api): array
    {
        $counts = ['covered' => 0, 'host' => 0, 'gap' => 0];
        foreach ($symbols as $symbol) {
            $status = (string) ($api[$symbol]['status'] ?? 'gap');
            if (isset($counts[$status])) {
                ++$counts[$status];
            }
        }

        return $counts;
    }

    /**
     * @param array<string, mixed> $entry
     */
    private static function row(string $symbol, array $entry): string
    {
        $status = self::STATUS_LABELS[(string) ($entry['status'] ?? '')] ?? 'unmapped';
        $artifact = (string) ($entry['artifact'] ?? '');
        $reason = (string) ($entry['reason'] ?? '');
        $detail = $artifact !== '' ? '`' . $artifact . '`' : '';
        if ($reason !== '') {
            $detail = $detail !== '' ? $detail . '; ' . self::cell($reason) : self::cell($reason);
        }

        return sprintf(
            '| `%s` | %s | %s | %s | %s |',
            $symbol,
            $status,
            $detail !== '' ? $detail : '—',
            self::list((array) ($entry['tests'] ?? [])),
            self::list((array) ($entry['e2e'] ?? [])),
        );
    }

    /**
     * @param array<mixed> $items
     */
    private static function list(array $items): string
    {
        if ($items === []) {
            return '—';
        }

        return implode('<br>', array_map(static fn (mixed $item): string => '`' . self::cell((string) $item) . '`', $items));
    }

    private static function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\|', ' '], $text);
    }
}
